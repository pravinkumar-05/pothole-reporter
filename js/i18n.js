// Export t function for dynamic text translation in JS
function t(key) {
    const lang = document.body.getAttribute('data-lang') || 'en';
    const dict = translations[lang] || translations.en;
    if (dict && dict[key] !== undefined) {
        return dict[key];
    }
    // Fallback to English
    if (translations.en && translations.en[key] !== undefined) {
        return translations.en[key];
    }
    return key;
}

// Apply translations to all elements with data-i18n attributes
function applyTranslations(lang) {
    const dict = translations[lang] || translations.en;
    if (!dict) return;

    // 1. data-i18n for text / html / options
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else if (el.tagName === 'OPTION') {
                el.textContent = dict[key];
            } else {
                el.innerHTML = dict[key];
            }
        }
    });

    // 2. data-i18n-placeholder explicitly for inputs and textareas
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });

    // 3. data-i18n-title for titles and tooltips
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key] !== undefined) {
            el.title = dict[key];
        }
    });

    // 4. Update Navigation role labels
    if (typeof updateNavAuth === 'function') {
        updateNavAuth();
    }

    // 5. Dispatch custom event for dynamic components (Dashboard, Table, Track, Maps)
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

// Set language and update entire application state
function setLanguage(lang) {
    if (!translations[lang]) lang = 'en';
    document.body.setAttribute('data-lang', lang);

    // Update active state on all language switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.textContent.trim().toLowerCase() === lang.toLowerCase());
    });

    // Apply translations across DOM
    applyTranslations(lang);

    // Persist user preference
    try {
        localStorage.setItem('roadguard_lang', lang);
    } catch(e) {}
}

// Initialize language on DOM ready
document.addEventListener('DOMContentLoaded', () => {
    let savedLang = 'en';
    try {
        savedLang = localStorage.getItem('roadguard_lang') || 'en';
    } catch(e) {}
    setLanguage(savedLang);
});
